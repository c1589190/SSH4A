import http.client
import json
import os
import socket
import subprocess
import sys
import time
from pathlib import Path

from .errors import AppError
from .profiles import port_number
from .storage import atomic_write, config_path

DEFAULT_PORT = 8744
UNIT = "ssh4a-mcp.service"
UNIT_MARKER = "# Generated by ssh4a"
PORT_MARKER = "# Port: "


def endpoint(port: int) -> str:
    return f"http://127.0.0.1:{port}/mcp"


def unit_location() -> Path:
    return config_path().parent / "systemd" / "user" / UNIT


def systemctl(*args, required=False):
    try:
        result = subprocess.run(
            ["systemctl", "--user", *args],
            text=True,
            capture_output=True,
            timeout=20,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise AppError(
            "service", "Could not contact the systemd user service manager"
        ) from exc
    if required and result.returncode:
        lines = result.stderr.strip().splitlines()
        raise AppError("service", lines[0] if lines else f"systemctl {args[0]} failed")
    return result


def unit_quote(value: str) -> str:
    return json.dumps(value.replace("%", "%%").replace("$", "$$"), ensure_ascii=False)


def configured_unit(path: Path) -> tuple[str | None, int]:
    try:
        content = path.read_text()
    except FileNotFoundError:
        return None, DEFAULT_PORT
    lines = content.splitlines()
    if (
        len(lines) < 2
        or lines[0] != UNIT_MARKER
        or not lines[1].startswith(PORT_MARKER)
    ):
        raise AppError("service", f"Existing {UNIT} is not managed by ssh4a")
    try:
        port = int(lines[1].removeprefix(PORT_MARKER))
    except ValueError as exc:
        raise AppError("service", f"Invalid port in {UNIT}") from exc
    return content, port_number(port)


def update_unit(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(path.parent, os.O_RDONLY | os.O_DIRECTORY)
    try:
        atomic_write(fd, path.name, content.encode())
    finally:
        os.close(fd)


def check_port(port: int) -> None:
    try:
        with socket.socket() as probe:
            probe.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            probe.bind(("127.0.0.1", port))
    except OSError as exc:
        raise AppError(
            "service", f"MCP port {port} is unavailable: {exc.strerror}"
        ) from exc


def wait_until_ready(port: int) -> None:
    stop = time.monotonic() + 10
    while time.monotonic() < stop:
        connection = http.client.HTTPConnection("127.0.0.1", port, timeout=0.3)
        try:
            connection.request("GET", "/mcp")
            response = connection.getresponse()
            if (
                response.status == 401
                and response.getheader("WWW-Authenticate") == 'Bearer realm="ssh4a"'
            ):
                return
        except (OSError, http.client.HTTPException):
            pass
        finally:
            connection.close()
        time.sleep(0.15)
    raise AppError(
        "service",
        f"MCP failed to become ready at {endpoint(port)}; check journalctl --user -u {UNIT}",
    )


def enable(config: Path, port: int) -> None:
    port_number(port)
    if os.geteuid() == 0:
        raise AppError("service", "Run the MCP service as its regular user")
    path = unit_location()
    original, old_port = configured_unit(path)
    active = systemctl("is-active", "--quiet", UNIT).returncode == 0
    enabled = systemctl("is-enabled", "--quiet", UNIT).returncode == 0
    if not active or old_port != port:
        check_port(port)
    command = [
        os.path.abspath(sys.executable),
        "-m",
        "ssh4a.cli",
        "--config-dir",
        str(config),
        "mcp",
        "serve",
        "--port",
        str(port),
    ]
    command_line = " ".join(unit_quote(part) for part in command)
    content = (
        f"{UNIT_MARKER}\n{PORT_MARKER}{port}\n"
        "[Unit]\nDescription=ssh4a local MCP service\n\n"
        f"[Service]\nExecStart={command_line}\n"
        "WorkingDirectory=%h\nRestart=on-failure\nRestartSec=1\n\n"
        "[Install]\nWantedBy=default.target\n"
    )
    changed = content != original
    if changed:
        update_unit(path, content)
    try:
        systemctl("daemon-reload", required=True)
        systemctl("enable", "--now", UNIT, required=True)
        if active and changed:
            systemctl("restart", UNIT, required=True)
        wait_until_ready(port)
    except AppError:
        if not enabled:
            systemctl("disable", UNIT)
        if not active:
            systemctl("stop", UNIT)
        if changed:
            if original is None:
                path.unlink(missing_ok=True)
            else:
                update_unit(path, original)
            systemctl("daemon-reload")
            if active:
                systemctl("restart", UNIT)
        raise


def disable() -> None:
    content, _ = configured_unit(unit_location())
    if content is not None:
        systemctl("disable", "--now", UNIT, required=True)


def status() -> dict:
    content, port = configured_unit(unit_location())
    service_state = systemctl("is-active", UNIT)
    enabled = systemctl("is-enabled", "--quiet", UNIT).returncode == 0
    try:
        linger = subprocess.run(
            [
                "loginctl",
                "show-user",
                str(os.geteuid()),
                "--property=Linger",
                "--value",
            ],
            text=True,
            capture_output=True,
            timeout=3,
            check=False,
        ).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        linger = ""
    return {
        "url": endpoint(port),
        "state": service_state.stdout.strip() or "unavailable",
        "installed": content is not None,
        "enabled": enabled,
        "linger": {"yes": True, "no": False}.get(linger),
    }
